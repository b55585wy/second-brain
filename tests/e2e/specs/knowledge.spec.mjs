import { test, expect } from '../support/fixtures.mjs';
import { apiData, createKnowledge, formWith, keyboardActivate, knowledgeCard, mutation, screenshot, searchKnowledge, synthetic } from '../support/ui.mjs';

test('KNOWLEDGE-01: manual source content and structured identities survive edit, acceptance and reload', async ({ page }, testInfo) => {
  const item = await createKnowledge(page);
  const card = knowledgeCard(page, item.question);
  const retentionBadge = card.getByTitle('接受状态仅表示是否保留，不代表事实正确。', { exact: true });
  const validationBadge = card.getByTitle('未事实核验：尚未进行证据核查，不代表内容正确或错误。', { exact: true });
  const validationStatus = item.validation?.status;
  expect(validationStatus ?? 'unverified', 'Fresh manual knowledge has no verified evidence.').toBe('unverified');
  await expect(card).toBeVisible();
  await expect(retentionBadge).toBeVisible();
  await expect(validationBadge).toHaveText('未核验');
  await expect(validationBadge).toBeVisible();
  await expect(card).toContainText(item.answer);
  await card.locator('summary').click();
  for (const source of item.sources) await expect(card.locator('details')).toContainText(source);
  await keyboardActivate(page, card.getByRole('button', { name: '编辑', exact: true }));
  const edit = formWith(page, '问题');
  for (const source of item.sources) await expect(edit).toContainText(source);
  const revisedAnswer = `${item.answer}\n${synthetic('knowledge-edit')}`;
  await edit.getByLabel('答案', { exact: true }).fill(revisedAnswer);
  const updated = await mutation(page, 'PATCH', `/api/v1/knowledge/${item.id}`, () => keyboardActivate(page, edit.getByRole('button', { name: '保存', exact: true })));
  const identities = item.sourceRefs.map(ref => ref.sourceId);
  expect(updated.request.postDataJSON().sourceRefs).toEqual(identities.map(sourceId => ({ sourceId })));
  expect(updated.data.validation?.status).toBe(validationStatus);
  const accepted = await mutation(page, 'POST', `/api/v1/knowledge/${item.id}/decision`, () => keyboardActivate(page, card.getByRole('button', { name: '接受', exact: true })));
  expect(accepted.data.status).toBe('accepted');
  expect(accepted.data.validation?.status, 'Acceptance must not promote factual validation.').toBe(validationStatus);
  await searchKnowledge(page, item.question);
  await page.getByRole('combobox', { name: '按状态筛选', exact: true }).selectOption('accepted');
  await expect(card).toBeVisible();
  await expect(retentionBadge).toHaveText('已接受');
  await expect(retentionBadge).toBeVisible();
  await expect(validationBadge).toHaveText('未核验');
  await expect(validationBadge).toBeVisible();
  await expect(card.getByText('证据支持', { exact: true })).toHaveCount(0);
  await screenshot(page, testInfo, 'synthetic-accepted-knowledge-sources');
  await page.reload();
  await searchKnowledge(page, item.question);
  await page.getByRole('combobox', { name: '按状态筛选', exact: true }).selectOption('accepted');
  await expect(card.getByRole('button', { name: '同步到思源', exact: true })).toBeVisible();
  await expect(card.getByRole('button', { name: '接受', exact: true })).toHaveCount(0);
  await expect(retentionBadge).toHaveText('已接受');
  await expect(validationBadge).toHaveText('未核验');
  await expect(validationBadge).toBeVisible();
  await expect(card).toContainText(revisedAnswer);
  await card.locator('summary').click();
  for (const source of item.sources) await expect(card.locator('details')).toContainText(source);
  const persisted = (await apiData(page, `/api/v1/knowledge?${new URLSearchParams({ q: item.question })}`)).items.find(record => record.id === item.id);
  expect(persisted.status).toBe('accepted');
  expect(persisted.validation?.status, 'Reload must preserve factual validation independently of retention.').toBe(validationStatus);
  expect(persisted.sourceRefs.map(ref => ref.sourceId)).toEqual(identities);
  expect(persisted.sourceRefs.map(ref => ref.excerpt)).toEqual(item.sources);
});

test('KNOWLEDGE-02: no-match search and rejected state are distinct from accepted knowledge', async ({ page }) => {
  const item = await createKnowledge(page);
  await searchKnowledge(page, synthetic('no-such-knowledge'));
  await expect(page.getByRole('heading', { name: '没有匹配的知识', exact: true })).toBeVisible();
  await expect(knowledgeCard(page, item.question)).toHaveCount(0);
  await searchKnowledge(page, item.question);
  const card = knowledgeCard(page, item.question);
  const rejected = await mutation(page, 'POST', `/api/v1/knowledge/${item.id}/decision`, () => keyboardActivate(page, card.getByRole('button', { name: '拒绝', exact: true })));
  expect(rejected.data.status).toBe('rejected');
  await page.getByRole('combobox', { name: '按状态筛选', exact: true }).selectOption('accepted');
  await expect(page.getByRole('heading', { name: '没有匹配的知识', exact: true })).toBeVisible();
  await page.reload();
  await searchKnowledge(page, item.question);
  await page.getByRole('combobox', { name: '按状态筛选', exact: true }).selectOption('rejected');
  await expect(card).toBeVisible();
  await expect(card.getByRole('button', { name: '接受', exact: true })).toHaveCount(0);
});
