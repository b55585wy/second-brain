import { test, expect } from '../support/fixtures.mjs';
import { createKnowledge, createOutput, createProject, keyboardActivate, noHorizontalOverflow, screenshot, synthetic } from '../support/ui.mjs';

test('VIEW-02 / NAV-01: mobile 390×844 navigation, synthetic records and forms have no overflow', async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '今天，从这里继续', level: 1, exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: '先设置学习目标', exact: true })).toBeVisible();
  const goalCta = page.getByRole('link', { name: '设置学习目标', exact: true });
  await expect(goalCta).toHaveCount(1);
  await expect(goalCta).toHaveAttribute('href', '/settings');
  await expect(goalCta).toBeVisible();
  await expect(page.getByRole('button', { name: /^(生成今日计划|重新安排今天)$/ })).toHaveCount(0);
  const menu = page.getByRole('button', { name: '打开导航', exact: true });
  await keyboardActivate(page, menu);
  await expect(page.getByRole('banner').getByRole('button', { name: '关闭导航', exact: true })).toHaveAttribute('aria-expanded', 'true');
  await keyboardActivate(page, page.getByRole('navigation', { name: '主导航', exact: true }).getByRole('link', { name: '项目', exact: true }));
  await expect(page).toHaveURL(/\/projects$/);
  await expect(menu).toHaveAttribute('aria-expanded', 'false');

  const project = await createProject(page, { title: synthetic('mobile-project'), goal: `${synthetic('mobile-goal')}\n${'验证'.repeat(80)}` });
  await noHorizontalOverflow(page);
  await keyboardActivate(page, page.getByRole('link', { name: project.title, exact: true }));
  await expect(page.getByLabel('本次进展', { exact: true })).toBeVisible();
  await noHorizontalOverflow(page);
  await screenshot(page, testInfo, 'synthetic-mobile-project-form');
  await createKnowledge(page, { question: synthetic('mobile-question'), answer: `${synthetic('mobile-answer')} <b>literal</b> ${'x'.repeat(200)}` });
  await noHorizontalOverflow(page);
  await screenshot(page, testInfo, 'synthetic-mobile-knowledge-long-text');
  await createOutput(page, { title: synthetic('mobile-output'), content: synthetic('mobile-output-content') });
  await noHorizontalOverflow(page);
  await screenshot(page, testInfo, 'synthetic-mobile-output-form');
  await page.goto('/settings');
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('');
  await noHorizontalOverflow(page);
  await screenshot(page, testInfo, 'synthetic-mobile-settings');
  await page.goto('/review');
  await expect(page.getByRole('heading', { name: '准备一次短复习', exact: true })).toBeVisible();
  await noHorizontalOverflow(page);
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '今天，从这里继续', level: 1, exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: '先设置学习目标', exact: true })).toBeVisible();
  await expect(goalCta).toHaveCount(1);
  await expect(goalCta).toHaveAttribute('href', '/settings');
  await expect(goalCta).toBeVisible();
  await expect(page.getByRole('button', { name: /^(生成今日计划|重新安排今天)$/ })).toHaveCount(0);
  await noHorizontalOverflow(page);
  await screenshot(page, testInfo, 'synthetic-mobile-today');
});
